#!/usr/bin/env python3
"""qflix-audit-live — the LIVE half of the Convergent Audit Regime (L-01..L-07).

Runs ON THE BOX, on its OWN timer, pushing its OWN Kuma monitor. It is
deliberately NOT folded into functional-audit.py or qflix-collect.py: the
operator design law is that every maintenance concern gets its own module, timer
and check so it stays independently swappable and tunable through a server
migration.

WHY THIS CANNOT BE PART OF qflix-audit.py
    Everything here is a property of a running machine, not of a commit:
      L-01 repo unit files vs DEPLOYED unit files (drop-ins like the reaper's
           `--max-pct 100` are DESIGNED to exist only on the box)
      L-02 deployed timers/services with no repo representation at all
      L-03 the live Kuma monitor set (kuma.db; /metrics lies for daily
           self-pushers, which drop out ~22h/day between beats)
      L-04 declared secret keys exist with a sane mode
      L-05 every self-pusher has a PERSISTED push token (the born-mute class)
      L-06 quota / thread-ceiling headroom
      L-07 stale-green push monitors (Kuma restart resets its push-timeout
           timers, so a monitor whose beat was already overdue at restart
           re-greens before it ever pages -- the missed run is invisible)
    These will keep producing new findings forever. That is registered honestly
    in docs/audit-residual-risk.md; it is not a defect of the design.

OUTPUT
    ~/.opt/maint/audit/last-audit.json, carrying a RECORD timestamp
    (`recorded_at`). The repo-side consumer must refuse a stale snapshot by
    RECORD time, never by file mtime — that is C-04 applied to the auditor
    itself, and it is the exact bug cbde5c1 fixed in REA.

EXIT CODES mirror the offline tool: 0 clean / 1 findings / 2 cannot audit.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import os
import re
import subprocess
import sys
from pathlib import Path

EXIT_OK, EXIT_FINDINGS, EXIT_CANNOT_AUDIT = 0, 1, 2

STATE_DIR = Path(os.environ.get("QFLIX_AUDIT_STATE",
                                str(Path.home() / ".opt" / "maint" / "audit")))
# COLON-separated list: QFlix stages units from more than one repo directory.
# A single dir made everything staged elsewhere look like it had no repo origin.
REPO_UNIT_DIRS = [
    Path(x) for x in os.environ.get(
        "QFLIX_AUDIT_REPO_UNITS",
        os.pathsep.join([
            str(Path.home() / "scripts" / "maint" / "systemd"),
            str(Path.home() / "scripts" / "mcp" / "systemd"),
            str(Path.home() / ".opt" / "qflix-src" / "scripts" / "maint" / "systemd"),
            str(Path.home() / ".opt" / "qflix-src" / "scripts" / "mcp" / "systemd"),
        ])
    ).split(os.pathsep) if x
]
REPO_UNITS = REPO_UNIT_DIRS[0]   # retained: single-dir callers/tests

# Units the maintenance system owns outright, in BOTH directions.
OWNED_UNIT_PREFIXES = ("manitoba-maint",)

# The jobs ledger on the box; `may_be_absent: true` opts a unit out of L-01.
JOBS_LEDGER = Path(os.environ.get(
    "QFLIX_AUDIT_JOBS_LEDGER",
    str(Path.home() / ".opt" / "maint" / "jobs.yaml")))


def _may_be_absent() -> set:
    """Unit basenames whose intended terminal state is 'gone'.

    flaresolverr-unsuppress deletes itself once FlareSolverr is healthy, so its
    absence is success, not drift. Declared in the ledger next to the job rather
    than hardcoded here, so the exemption lives where the job does.
    """
    try:
        import yaml                                            # noqa: PLC0415
        data = yaml.safe_load(JOBS_LEDGER.read_text(encoding="utf-8")) or {}
    except Exception:                                          # noqa: BLE001
        return set()
    out = set()
    for _name, v in (data.get("jobs") or {}).items():
        if isinstance(v, dict) and v.get("may_be_absent") and v.get("timer"):
            stem = os.path.basename(str(v["timer"]))
            out.add(stem)
            out.add(stem[:-len(".timer")] + ".service")
    return out


def _is_owned(unit: str, repo_units: set) -> bool:
    """In scope iff plainly ours, or the repo actually ships it.

    Apps whose units are generated by their own installer (kometa, buildarr,
    recyclarr, upgradinatorr, tdarr-node-*, qflix-dash) have no repo unit file by
    design; so do Ultra.cc panel apps (nginx, qbittorrent, listmonk). Neither is
    drift, and flagging them is exactly the false-red noise this regime exists to
    remove.
    """
    return unit.startswith(OWNED_UNIT_PREFIXES) or unit in repo_units
DEPLOYED_UNITS = Path(os.environ.get("QFLIX_AUDIT_DEPLOYED_UNITS",
                                     str(Path.home() / ".config" / "systemd" / "user")))
SECRETS_DIR = Path(os.environ.get("MANITOBA_SECRETS",
                                  str(Path.home() / "secrets")))
KUMA_DB = Path(os.environ.get("QFLIX_KUMA_DB",
                              str(Path.home() / ".apps" / "uptimekuma" / "kuma.db")))
PUSH_TOKENS = SECRETS_DIR / "kuma-push-tokens.json"

MONITOR_NAME = "QFlix Audit Live"
# Token KEY in ~/secrets/kuma-push-tokens.json. Must equal the VALUE this monitor
# is registered under in lib/kuma.py STANDALONE_SELF_PUSH_MONITORS, or the push
# silently no-ops and the monitor goes red for entirely the wrong reason.
KUMA_PUSH_KEY = "qflix-audit-live"


# ---------------------------------------------------------------------------
# pure helpers — unit-tested offline in tests/unit/test_audit_live.py
# ---------------------------------------------------------------------------

def diff_unit_sets(repo: set[str], deployed: set[str]) -> dict[str, list[str]]:
    """L-01/L-02 in their set-theoretic form.

    `deployed_only` is the interesting direction — a unit running on the box that
    no commit describes. `repo_only` is usually benign (units the installer has
    not been asked to enable yet) and is reported at a lower severity.
    """
    return {
        "deployed_only": sorted(deployed - repo),
        "repo_only": sorted(repo - deployed),
        "both": sorted(repo & deployed),
    }


def classify_secret_mode(mode: int) -> str:
    """L-04. World- or group-readable secrets on a SHARED seedbox are the whole
    threat model, so anything past 0600 is called out."""
    if mode & 0o077:
        return "too-permissive"
    return "ok"


def missing_push_tokens(expected: list[str], tokens: dict) -> list[str]:
    """L-05, the born-mute class.

    A canary whose token was never persisted exits 0 in silence and its monitor
    never beats — 32 of 60 monitors were once in some flavour of this state, and
    the reaper's forever-red was a never-persisted token. An empty-string value
    counts as missing: that is precisely how it failed before.
    """
    return sorted(name for name in expected
                  if not str(tokens.get(name) or "").strip())


def parse_quota_pct(df_line: str) -> int | None:
    """L-06. Accepts a `df -P` style line; returns the used percentage."""
    m = re.search(r"(\d+)%", df_line or "")
    return int(m.group(1)) if m else None


def snapshot_is_stale(payload: dict, now: _dt.datetime, max_age_min: int) -> bool:
    """Freshness by RECORD time, never by file mtime.

    A rewritten-in-place file looks fresh to stat(2) while carrying week-old
    content. This is the C-04 class applied to the audit's own artefact.
    """
    raw = (payload or {}).get("recorded_at")
    if not raw:
        return True
    try:
        ts = _dt.datetime.fromisoformat(str(raw).replace("Z", "+00:00"))
    except ValueError:
        return True
    if ts.tzinfo is None:
        ts = ts.replace(tzinfo=_dt.timezone.utc)
    return (now - ts).total_seconds() / 60.0 > max_age_min


