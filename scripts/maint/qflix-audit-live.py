def _unit_names(directory: Path) -> set[str]:
    try:
        return {p.name for p in directory.iterdir()
                if p.suffix in (".service", ".timer")}
    except OSError:
        return set()


def _kuma_monitor_names() -> set[str] | None:
    if not KUMA_DB.exists():
        return None
    try:
        import sqlite3
        con = sqlite3.connect(f"file:{KUMA_DB}?mode=ro", uri=True, timeout=3)
        try:
            rows = con.execute("SELECT name FROM monitor WHERE active=1").fetchall()
        finally:
            con.close()
        return {r[0] for r in rows if r and r[0]}
    except Exception as exc:                                  # noqa: BLE001
        print(f"qflix-audit-live: kuma.db unreadable: {exc}", file=sys.stderr)
        return None


def stale_green_pushers(rows, now: _dt.datetime, slack: float = 1.25) -> list[dict]:
    """L-07, the pure half. `rows` = (name, interval_s, last_beat_utc_str,
    last_status); returns a finding per ACTIVE push monitor whose latest beat
    is GREEN yet older than its own heartbeat window (with slack).

    WHY (2026-08-18 storm audit): Kuma's push-timeout timers live in process
    memory and RESET when Kuma restarts. The host reboot took Kuma down
    04:38-07:36 UTC; the daily self-pushers (reaper, torrent-janitor, audit
    regime) had all just failed against dead services, and on restart their
    25h deadlines were re-armed FROM KUMA BOOT -- pushed past each job's next
    scheduled run, so all three sat GREEN on 36-38h-old beats and the lost
    day could never page. Contrast the REA-liveness canary (70min window):
    its re-armed deadline expired BEFORE the next beat, so it alone paged.

    The slack factor absorbs RandomizedDelaySec and one slow run; 1.25 x 25h
    ~= 31h, well under the 2-day age that means a genuinely lost run.

    Fails open per row: an unparseable beat time yields no finding -- this
    detector exists to catch silence, not to manufacture it from format
    drift. (Kuma writes naive UTC 'YYYY-MM-DD HH:MM:SS.mmm' today.)
    """
    out = []
    for name, interval_s, beat_time, status in rows:
        if status != 1 or not interval_s:
            continue  # red monitors already page; interval 0 has no window
        try:
            t = _dt.datetime.fromisoformat(str(beat_time).split(".")[0])
            t = t.replace(tzinfo=_dt.timezone.utc)
        except ValueError:
            continue
        age = (now - t).total_seconds()
        if age > interval_s * slack:
            out.append({
                "class_id": "L-07", "instance_id": name,
                "detail": "stale-green-%dh-beat-vs-%dh-window"
                          % (age // 3600, interval_s // 3600),
            })
    return out


def _push_monitor_beats():
    """DB half of L-07: (name, interval, latest beat time, latest status) for
    every ACTIVE push-type monitor. None when kuma.db is not readable."""
    if not KUMA_DB.exists():
        return None
    try:
        import sqlite3
        con = sqlite3.connect(f"file:{KUMA_DB}?mode=ro", uri=True, timeout=3)
        try:
            rows = con.execute(
                "SELECT m.name, m.interval, h.time, h.status "
                "FROM monitor m JOIN heartbeat h ON h.id = ("
                "  SELECT id FROM heartbeat WHERE monitor_id = m.id "
                "  ORDER BY time DESC LIMIT 1) "
                "WHERE m.active = 1 AND m.type = 'push'").fetchall()
        finally:
            con.close()
        return rows
    except Exception as exc:                                  # noqa: BLE001
        print(f"qflix-audit-live: kuma.db unreadable for L-07: {exc}",
              file=sys.stderr)
        return None


def collect(expected_monitors: list[str]) -> dict:
    findings: list[dict] = []
    coverage: dict[str, str] = {}

    # L-01 / L-02 ---------------------------------------------------------
    repo_units = set()
    for _d in REPO_UNIT_DIRS:
        repo_units |= _unit_names(_d)
    # Only adjudicate what we own; installer-generated and panel-managed units
    # are out of scope both ways. Exempt units whose terminal state is "gone".
    _exempt = _may_be_absent()
    repo_units = {u for u in repo_units
                  if u.startswith(OWNED_UNIT_PREFIXES) and u not in _exempt}
    deployed_units = {u for u in _unit_names(DEPLOYED_UNITS)
                      if _is_owned(u, repo_units) and u not in _exempt}
    if not repo_units or not deployed_units:
        coverage["L-01"] = coverage["L-02"] = "unavailable"
    else:
        diff = diff_unit_sets(repo_units, deployed_units)
        coverage["L-01"] = coverage["L-02"] = "checked"
        for name in diff["deployed_only"]:
            findings.append({"class_id": "L-02", "instance_id": name,
                             "detail": "deployed-unit-not-in-repo"})
        for name in diff["repo_only"]:
            findings.append({"class_id": "L-01", "instance_id": name,
                             "detail": "repo-unit-not-deployed"})

    # L-03 ---------------------------------------------------------------
    live = _kuma_monitor_names()
    if live is None:
        coverage["L-03"] = "unavailable"
    else:
        coverage["L-03"] = "checked"
        for name in sorted(set(expected_monitors) - live):
            findings.append({"class_id": "L-03", "instance_id": name,
                             "detail": "expected-monitor-absent-from-kuma"})

    # L-04 ---------------------------------------------------------------
    if SECRETS_DIR.is_dir():
        coverage["L-04"] = "checked"
        for p in sorted(SECRETS_DIR.iterdir()):
            if not p.is_file():
                continue
            verdict = classify_secret_mode(p.stat().st_mode & 0o777)
            if verdict != "ok":
                findings.append({"class_id": "L-04", "instance_id": p.name,
                                 "detail": f"secret-mode-{verdict}"})
    else:
        coverage["L-04"] = "unavailable"

    # L-05 ---------------------------------------------------------------
    if PUSH_TOKENS.exists():
        coverage["L-05"] = "checked"
        try:
            tokens = json.loads(PUSH_TOKENS.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            coverage["L-05"] = "unavailable"
            print(f"qflix-audit-live: push tokens unreadable: {exc}", file=sys.stderr)
            tokens = {}
        for name in missing_push_tokens(expected_monitors, tokens):
            findings.append({"class_id": "L-05", "instance_id": name,
                             "detail": "self-pusher-without-persisted-token"})
    else:
        coverage["L-05"] = "unavailable"

    # L-06 ---------------------------------------------------------------
    proc = subprocess.run(["df", "-P", str(Path.home())],
                          capture_output=True, text=True, check=False)
    pct = None
    if proc.returncode == 0:
        lines = proc.stdout.strip().splitlines()
        if len(lines) >= 2:
            pct = parse_quota_pct(lines[1])
    if pct is None:
        coverage["L-06"] = "unavailable"
    else:
        coverage["L-06"] = "checked"
        if pct >= 90:
            findings.append({"class_id": "L-06", "instance_id": "home-quota",
                             "detail": f"quota-{pct}pct"})

    # L-07 ---------------------------------------------------------------
    beats = _push_monitor_beats()
    if beats is None:
        coverage["L-07"] = "unavailable"
    else:
        coverage["L-07"] = "checked"
        findings.extend(
            stale_green_pushers(beats, _dt.datetime.now(_dt.timezone.utc)))

    return {"coverage": coverage, "findings": findings}


def _push_kuma(status: str, msg: str) -> None:
    """Best-effort heartbeat for this auditor's OWN monitor.

    The module docstring said "pushing its OWN Kuma monitor" and main() never
    did. The monitor was registered, given a token, and fed by nobody, so it
    would have gone red on heartbeat timeout -- the born-dead class L-05 exists
    to detect, occurring inside the detector itself.

    A MISSING TOKEN IS REPORTED, never silently skipped: a silent skip is the
    C-09 class this regime enumerates, and the auditor does not get to be an
    instance of it.
    """
    import urllib.parse
    import urllib.request

    token = os.environ.get("QFLIX_AUDIT_LIVE_KUMA_TOKEN", "")
    if not token:
        try:
            data = json.loads(PUSH_TOKENS.read_text(encoding="utf-8"))
            token = str(data.get(KUMA_PUSH_KEY, "") or "")
        except (OSError, ValueError):
            token = ""
    if not token:
        print("qflix-audit-live: WARNING no Kuma push token under '"
              + KUMA_PUSH_KEY + "' - heartbeat NOT pushed; monitor '"
              + MONITOR_NAME + "' will go red, correctly", file=sys.stderr)
        return

    try:
        port = (SECRETS_DIR / "uptimekuma.port").read_text(encoding="utf-8").strip()
    except OSError:
        port = ""
    if not port:
        print("qflix-audit-live: WARNING no uptimekuma.port - heartbeat NOT pushed",
              file=sys.stderr)
        return

    qs = urllib.parse.urlencode({"status": status, "msg": msg[:200]})
    url = "http://127.0.0.1:" + port + "/api/push/" + token + "?" + qs
    try:
        with urllib.request.urlopen(url, timeout=15) as resp:
            resp.read()
    except Exception as exc:                                  # noqa: BLE001
        print("qflix-audit-live: heartbeat push failed: " + repr(exc),
              file=sys.stderr)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="qflix-audit-live", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--push-kuma", action="store_true",
                    help="push a heartbeat to this auditor's own Kuma monitor")
    ap.add_argument("--expected-monitors", default="",
                    help="comma-separated monitor names expected to exist")
    args = ap.parse_args(argv)

    expected = [m.strip() for m in args.expected_monitors.split(",") if m.strip()]
    result = collect(expected)
    result["recorded_at"] = _dt.datetime.now(
        _dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    result["monitor"] = MONITOR_NAME

    try:
        STATE_DIR.mkdir(parents=True, exist_ok=True)
        (STATE_DIR / "last-audit.json").write_text(
            json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    except OSError as exc:
        # Loud, not silent: an audit whose artefact never lands is an audit that
        # did not happen, and this is exactly the class C-09 is about.
        print(f"qflix-audit-live: cannot write state: {exc}", file=sys.stderr)
        return EXIT_CANNOT_AUDIT

    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True))
    else:
        print(f"qflix-audit-live: {len(result['findings'])} findings; "
              f"coverage={result['coverage']}")

    partial = any(v == "unavailable" for v in result["coverage"].values())
    if partial:
        # "I could not look" must never be reported as "I looked and it is fine".
        print("qflix-audit-live: some live classes were UNAVAILABLE — "
              "treat this run as partial", file=sys.stderr)

    if args.push_kuma:
        # DOWN on drift, and DOWN on partial coverage. Drift means the box no
        # longer matches the repo, which is the entire reason this runs; and a
        # run that could not look must never read as a clean one.
        n = len(result["findings"])
        if n:
            kinds = sorted({f.get("class", "?") for f in result["findings"]})
            _push_kuma("down",
                       "live-drift " + str(n) + " finding(s): " + ",".join(kinds))
        elif partial:
            unavail = sorted(k for k, v in result["coverage"].items()
                             if v == "unavailable")
            _push_kuma("down", "PARTIAL - could not check: " + ",".join(unavail))
        else:
            checked = sorted(k for k, v in result["coverage"].items()
                             if v == "checked")
            _push_kuma("up", "live audit clean: " + ",".join(checked))

    return EXIT_FINDINGS if result["findings"] else EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
